// Bundles the legal documents' markdown into modules the app can import.
//
// The documents are prose (`content/legal/<locale>/<document>.md`, a title and
// a description in the frontmatter, then the body), and they are read on pages
// that render on demand in production, where `output: "standalone"` ships no
// file a module does not import. So, like the glossary, each language becomes
// one generated module, loaded only by the reader who asks for it.
//
// English is the only tree anyone writes. The other languages are filled in by
// `generate-legal-translations.ts`, in CI, and a document a language does not
// hold yet falls back to English rather than 404ing.
//
//   pnpm --filter @unicum.gg/web exec tsx scripts/generate-legal.ts
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { frontmatter } from "fumadocs-core/content/md/frontmatter";

const webRoot = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const CONTENT_DIR = join(webRoot, "content", "legal");
const OUT_DIR = join(webRoot, "src", "services", "legal", "generated");
const SOURCE_LOCALE = "en";
/** Kept in step with `LegalDocumentId`, which this script cannot import
 * without pulling the app's module graph into postinstall. */
const DOCUMENTS = ["company", "privacy", "terms"] as const;

const HEADER = `// Generated by scripts/generate-legal.ts from content/legal. Do not edit.`;

type Doc = { title: string; description: string; body: string };

function readLocale(locale: string, strict: boolean): Partial<Record<string, Doc>> {
  const out: Partial<Record<string, Doc>> = {};
  for (const id of DOCUMENTS) {
    const path = join(CONTENT_DIR, locale, `${id}.md`);
    if (!existsSync(path)) {
      if (strict) throw new Error(`[legal] missing ${path}`);
      continue;
    }
    const { data, content } = frontmatter(readFileSync(path, "utf8"));
    const front = data as { title?: unknown; description?: unknown };
    if (typeof front.title !== "string" || typeof front.description !== "string") {
      throw new Error(`[legal] ${locale}/${id}.md needs a title and a description`);
    }
    out[id] = { title: front.title, description: front.description, body: content.trim() };
  }
  return out;
}

function main() {
  mkdirSync(OUT_DIR, { recursive: true });
  const english = readLocale(SOURCE_LOCALE, true);
  const locales = [SOURCE_LOCALE];
  writeFileSync(join(OUT_DIR, `${SOURCE_LOCALE}.ts`), moduleFor(english));

  for (const dir of readdirSync(CONTENT_DIR, { withFileTypes: true })) {
    if (!dir.isDirectory() || dir.name === SOURCE_LOCALE) continue;
    const docs = readLocale(dir.name, false);
    if (Object.keys(docs).length === 0) continue;
    writeFileSync(join(OUT_DIR, `${dir.name}.ts`), moduleFor(docs));
    locales.push(dir.name);
  }

  writeFileSync(
    join(OUT_DIR, "index.ts"),
    `${HEADER}
export type LegalDocumentContent = { title: string; description: string; body: string };
type Documents = Partial<Record<string, LegalDocumentContent>>;

async function load(locale: string): Promise<Documents> {
  switch (locale) {
${locales
  .map((l) => `    case ${JSON.stringify(l)}:\n      return (await import(${JSON.stringify(`./${l}`)})).default;`)
  .join("\n")}
    default:
      return {};
  }
}

/** One document in one language, English when that language lacks it. */
export async function loadLegalDocument(
  locale: string,
  id: string,
): Promise<{ content: LegalDocumentContent; locale: string }> {
  const own = (await load(locale))[id];
  if (own) return { content: own, locale };
  const english = (await load(${JSON.stringify(SOURCE_LOCALE)}))[id];
  if (!english) throw new Error(\`no legal document "\${id}"\`);
  return { content: english, locale: ${JSON.stringify(SOURCE_LOCALE)} };
}
`,
  );
  console.log(`[legal] ${DOCUMENTS.length} documents → src/services/legal/generated, locales: ${locales.join(", ")}`);
}

function moduleFor(docs: Partial<Record<string, Doc>>): string {
  return `${HEADER}
const documents: Partial<Record<string, { title: string; description: string; body: string }>> = ${JSON.stringify(docs, null, 2)};

export default documents;
`;
}

main();
