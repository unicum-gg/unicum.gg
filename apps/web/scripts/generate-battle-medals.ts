// The medals a battle awards, from the game's own record ids to their names.
//
//   tsx scripts/generate-battle-medals.ts
//
// A battle's results name its medals by the dossier's numeric record id
// (`[228, 521, 39]`), and nothing on the site could say which medal that is.
// The client's `dossiers2/custom/records.py` holds the table (`RECORD_DB_IDS`,
// `('achievements', 'mainGun'): 228`), and the name is also the medal's picture
// in the assets mirror (`gui/maps/icons/achievement/mainGun.png`) and its key in
// Wargaming's achievement catalogue. Generated rather than copied, like the
// event modes, so a medal the game adds arrives on the next build.
//
// A failed read keeps the file already committed: the table only grows, and a
// build must not lose every medal because the mirror did not answer once.
import { existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { rawUrl, WotSrcBranch } from "@unicum.gg/wargaming/source/wot/mirror";

const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  "../../../packages/shared/src/wot/battle-medals.generated.ts",
);
const RECORDS = "sources/res/scripts/common/dossiers2/custom/records.py";

/**
 * The record blocks that hold medals a battle can award. The Steam client's
 * copies are left out: they repeat a medal under another id, have no picture
 * of their own, and are awarded beside the real one.
 */
const MEDAL_BLOCK = /^(?!steam)[A-Za-z0-9]*[Aa]chievements[A-Za-z0-9]*$/;

async function main(): Promise<void> {
  let text: string;
  try {
    const response = await fetch(rawUrl(WotSrcBranch.EU, RECORDS));
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    text = await response.text();
  } catch (error) {
    if (existsSync(OUT)) {
      console.warn(`[battle-medals] mirror unreachable (${String(error)}), keeping the committed table`);
      return;
    }
    throw error;
  }
  const start = text.indexOf("RECORD_DB_IDS = {");
  const end = text.indexOf("DB_ID_TO_RECORD", start);
  if (start < 0 || end < 0) throw new Error("RECORD_DB_IDS not found in records.py");
  const medals = new Map<number, string>();
  for (const found of text
    .slice(start, end)
    .matchAll(/\('([A-Za-z0-9_]+)',\s*'([A-Za-z0-9_]+)'\):\s*(\d+)/g)) {
    const [, block, name, id] = found;
    if (MEDAL_BLOCK.test(block)) medals.set(Number(id), name);
  }
  if (medals.size < 100) throw new Error(`only ${medals.size} medals read, refusing to write`);
  const rows = [...medals]
    .sort(([a], [b]) => a - b)
    .map(([id, name]) => `  ${id}: "${name}",`)
    .join("\n");
  writeFileSync(
    OUT,
    `// Generated by apps/web/scripts/generate-battle-medals.ts from the client's
// dossiers2/custom/records.py. Do not edit by hand.

/** A battle medal's record id to its name, which is also its picture's file name. */
export const BATTLE_MEDALS: Readonly<Record<number, string>> = {
${rows}
};
`,
  );
  console.log(`[battle-medals] ${medals.size} medal(s) -> ${OUT}`);
}

main().catch((error) => {
  console.error("[battle-medals] failed:", error);
  process.exit(1);
});
